import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pathToFileURL } from 'node:url';
import { readCatalog, shotWall, collectUnitStyles } from '../vendor/templates/_kit/render.mjs';

/**
 * 模板构建：`shots/*.json` + `_kit/` → `pages/*.html` 与 `film.html`。
 *
 *   node scripts/templates-build.mjs            # 写出所有模板
 *   node scripts/templates-build.mjs --check    # 只比对，不写；不一致则退出码 1（测试用）
 *   node scripts/templates-build.mjs paper-texture
 *
 * 生成的页面是提交进仓库的：模板在 OpenFilm 里是静态 HTML，运行时不跑任何
 * 构建步骤。所以"源"是 JSON 与单元，产物是页面，两边都要在版本库里。
 */

const root = fileURLToPath(new URL('../', import.meta.url));
const templatesRoot = join(root, 'vendor', 'templates');
const args = process.argv.slice(2);
const check = args.includes('--check');
const only = args.find(arg => !arg.startsWith('--'));

const catalog = readCatalog();

function listShots(templateDir) {
  const dir = join(templateDir, 'shots');
  return readdirSync(dir)
    .filter(name => name.endsWith('.json'))
    .sort()
    .map(name => ({ name, shot: JSON.parse(readFileSync(join(dir, name), 'utf8')) }));
}

const planned = [];

for (const name of readdirSync(templatesRoot).sort()) {
  if (name.startsWith('_') || (only && name !== only)) continue;
  const templateDir = join(templatesRoot, name);
  const configPath = join(templateDir, 'template.json');
  if (!existsSync(configPath) || !existsSync(join(templateDir, 'shots'))) continue;

  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const rendererPath = join(templatesRoot, '_kit', config.kit, 'page.mjs');
  const { render, clock } = await import(pathToFileURL(rendererPath).href);
  const shots = listShots(templateDir);

  let cursor = 0;
  const entries = shots.map(({ shot }, index) => {
    const start = clock ? clock(shot) : cursor;
    cursor = start + shot.duration;
    return { shot, start, order: String(index + 1).padStart(2, '0') };
  });

  // A template directory must be self-contained: installing a template copies
  // that directory into the project, so a link to a sibling `_kit` would break.
  // The kit stays the source; this file is the emitted copy.
  const usedUnits = entries.flatMap(({ shot }) => shot.units ?? []);
  const read = (rel) => readFileSync(join(templatesRoot, rel), 'utf8').trim();
  if (usedUnits.length) {
    const kitCss = collectUnitStyles(usedUnits, catalog);
    const shared = (config.sharedStyles ?? []).map(read).join('\n');
    planned.push({
      path: join(templateDir, 'assets', 'kit.css'),
      body: `/* Generated by scripts/templates-build.mjs from vendor/templates/_kit. Do not edit. */\n${shared}\n${kitCss}\n`,
    });
  }

  // Scripts a template shares are emitted beside its pages for the same reason
  // as kit.css: installing a template copies only that one directory, so a
  // <script src="../../_kit/..."> would 404 in the user's project.
  for (const rel of config.sharedScripts ?? []) {
    planned.push({
      path: join(templateDir, 'assets', rel.split('/').pop()),
      body: `/* Generated by scripts/templates-build.mjs from vendor/templates/_kit. Do not edit. */\n${read(rel)}\n`,
    });
  }

  for (const { shot } of entries) {
    planned.push({
      path: join(templateDir, 'pages', `${shot.id}.html`),
      body: render(shot, catalog, { templateDir }),
    });
  }
  planned.push({
    path: join(templateDir, 'film.html'),
    body: shotWall({
      title: config.wallTitle,
      size: config.size ?? [1080, 1920],
      backdrop: config.wallBackdrop,
      sectionTitle: config.sectionTitle,
      shots: entries.map(({ shot, start, order }) => ({ id: shot.id, title: shot.title, duration: shot.duration, start, order })),
    }),
  });
}

let changed = 0;
for (const file of planned) {
  if (check) {
    const current = existsSync(file.path) ? readFileSync(file.path, 'utf8') : null;
    if (current !== file.body) {
      changed += 1;
      console.error(`out of date: ${file.path.replace(root, '')} (run: node scripts/templates-build.mjs)`);
    }
    continue;
  }
  mkdirSync(dirname(file.path), { recursive: true });
  const current = existsSync(file.path) ? readFileSync(file.path, 'utf8') : null;
  if (current === file.body) continue;
  writeFileSync(file.path, file.body, 'utf8');
  changed += 1;
  console.log(`wrote ${file.path.replace(root, '')}`);
}

if (check && changed) process.exitCode = 1;
else if (!check) console.log(`${changed} file(s) updated, ${planned.length} checked`);
